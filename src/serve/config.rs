//! Generating the nginx and PHP configuration Wisp needs to serve a project.
//!
//! Everything is written fresh from the database on each sync, so the generated
//! files are a function of the project records rather than hand-edited state.

use std::path::{Path, PathBuf};

/// The nginx prefix for an installed version (`conf/`, `logs/`, `nginx.exe`).
pub fn nginx_prefix(version: &str) -> PathBuf {
    crate::runtime::install_dir(crate::runtime::RuntimeKind::Nginx, version)
}

/// Where Wisp writes the nginx configurations it owns.
pub fn conf_dir(prefix: &Path) -> PathBuf {
    prefix.join("conf")
}

/// Generated per-project server blocks, `include`d by the main config.
pub fn vhosts_dir(prefix: &Path) -> PathBuf {
    conf_dir(prefix).join("wisp-sites")
}

/// The main config Wisp runs nginx with, leaving the stock `nginx.conf` alone.
pub fn main_config_path(prefix: &Path) -> PathBuf {
    conf_dir(prefix).join("wisp.conf")
}

/// Per-project generated `php.ini` and logs.
pub fn site_dir(slug: &str) -> PathBuf {
    crate::config::sites().join(slug)
}

pub fn site_logs(slug: &str) -> PathBuf {
    site_dir(slug).join("logs")
}

/// The main nginx configuration.
pub fn main_config() -> String {
    "\
worker_processes  1;
pid        logs/nginx.pid;
error_log  logs/error.log;

events {
    worker_connections  1024;
}

http {
    include       mime.types;
    default_type  application/octet-stream;

    access_log    logs/access.log;

    # Windows has no efficient sendfile; nginx docs recommend disabling it.
    sendfile           off;
    keepalive_timeout  65;
    client_max_body_size 128m;

    include       wisp-sites/*.conf;
}
"
    .to_string()
}

/// The port nginx listens on for HTTP. Port 80 by default, overridable via
/// `WISP_HTTP_PORT` for tests or when something else already holds port 80.
pub fn http_port() -> u16 {
    std::env::var("WISP_HTTP_PORT")
        .ok()
        .and_then(|value| value.parse().ok())
        .unwrap_or(80)
}

/// A generated server block for one project.
pub struct Vhost<'a> {
    pub domain: &'a str,
    pub docroot: &'a Path,
    pub port: u16,
    pub listen_port: u16,
    pub log_dir: &'a Path,
}

impl Vhost<'_> {
    pub fn render(&self) -> String {
        let root = nginx_path(self.docroot);
        let access = nginx_path(&self.log_dir.join("access.log"));
        let error = nginx_path(&self.log_dir.join("error.log"));

        format!(
            "\
# Generated by Wisp. Do not edit; change the project in the app instead.
server {{
    listen       {listen_port};
    server_name  {domain};

    root  \"{root}\";
    index index.php index.html index.htm;

    access_log  \"{access}\";
    error_log   \"{error}\";

    location / {{
        try_files $uri $uri/ /index.php?$query_string;
    }}

    location ~ \\.php$ {{
        fastcgi_pass   127.0.0.1:{port};
        fastcgi_index  index.php;
        include        fastcgi_params;
        fastcgi_param  SCRIPT_FILENAME  $document_root$fastcgi_script_name;
    }}

    # Never serve dotfiles, except the ACME challenge path.
    location ~ /\\.(?!well-known).* {{
        deny all;
    }}
}}
",
            listen_port = self.listen_port,
            domain = self.domain,
            root = root,
            access = access,
            error = error,
            port = self.port,
        )
    }
}

/// Build a per-project `php.ini` from the runtime's `php.ini-development`
/// template, appending the development overrides Wisp wants.
pub fn php_ini(template: &str, extension_dir: &Path, error_log: &Path) -> String {
    let extension_dir = nginx_path(extension_dir);
    let error_log = nginx_path(error_log);
    format!(
        "{template}\n\
; ---- Wisp overrides -------------------------------------------------------\n\
cgi.fix_pathinfo=0\n\
extension_dir=\"{extension_dir}\"\n\
log_errors=On\n\
display_errors=On\n\
display_startup_errors=On\n\
error_reporting=E_ALL\n\
error_log=\"{error_log}\"\n\
date.timezone=UTC\n\
memory_limit=512M\n\
upload_max_filesize=64M\n\
post_max_size=64M\n\
max_execution_time=120\n\
"
    )
}

/// The document root for a project: `public/` when that is how the app is laid
/// out (Laravel, Symfony), otherwise the root itself.
pub fn resolve_docroot(root: &Path) -> PathBuf {
    if root.join("index.php").is_file() {
        return root.to_path_buf();
    }
    let public = root.join("public");
    if public.join("index.php").is_file() {
        return public;
    }
    root.to_path_buf()
}

/// nginx wants forward slashes, even on Windows.
fn nginx_path(path: &Path) -> String {
    path.to_string_lossy().replace('\\', "/")
}

#[cfg(test)]
mod tests {
    use super::{php_ini, resolve_docroot, Vhost};
    use std::path::{Path, PathBuf};

    #[test]
    fn a_vhost_points_at_the_docroot_and_fastcgi_port() {
        let vhost = Vhost {
            domain: "myapp.test",
            docroot: Path::new(r"C:\Sites\myapp\public"),
            port: 9071,
            listen_port: 80,
            log_dir: Path::new(r"C:\Users\me\.config\wisp\sites\myapp\logs"),
        }
        .render();

        assert!(vhost.contains("listen       80;"));
        assert!(vhost.contains("server_name  myapp.test;"));
        assert!(vhost.contains("root  \"C:/Sites/myapp/public\";"));
        assert!(vhost.contains("fastcgi_pass   127.0.0.1:9071;"));
        assert!(vhost.contains("try_files $uri $uri/ /index.php?$query_string;"));
        assert!(vhost.contains(r#"error_log   "C:/Users/me/.config/wisp/sites/myapp/logs/error.log";"#));
    }

    #[test]
    fn php_overrides_are_appended_after_the_template() {
        let ini = php_ini(
            "memory_limit=128M\n",
            Path::new(r"C:\php\ext"),
            Path::new(r"C:\logs\php-error.log"),
        );
        // The override must win, which means appearing later in the file.
        let template_at = ini.find("memory_limit=128M").unwrap();
        let override_at = ini.find("memory_limit=512M").unwrap();
        assert!(override_at > template_at);
        assert!(ini.contains(r#"extension_dir="C:/php/ext""#));
        assert!(ini.contains("cgi.fix_pathinfo=0"));
        assert!(ini.contains(r#"error_log="C:/logs/php-error.log""#));
    }

    #[test]
    fn a_public_folder_is_used_when_present() {
        let root = std::env::temp_dir().join("wisp-docroot-test");
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(root.join("public")).unwrap();
        std::fs::write(root.join("public").join("index.php"), "<?php").unwrap();

        assert_eq!(resolve_docroot(&root), root.join("public"));

        // Once the app evolves to put index.php at the root, that wins.
        std::fs::write(root.join("index.php"), "<?php").unwrap();
        assert_eq!(resolve_docroot(&root), root);

        let _ = std::fs::remove_dir_all(&root);
        let _ = root;
        let _: PathBuf = PathBuf::new();
    }
}
