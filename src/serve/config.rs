//! Generating the nginx and PHP configuration Wisp needs to serve a project.
//!
//! Everything is written fresh from the database on each sync, so the generated
//! files are a function of the project records rather than hand-edited state.

use std::path::{Path, PathBuf};

use crate::tls::TlsPaths;

/// The nginx prefix for an installed version (`conf/`, `logs/`, `nginx.exe`).
pub fn nginx_prefix(version: &str) -> PathBuf {
    crate::runtime::install_dir(crate::runtime::RuntimeKind::Nginx, version)
}

/// Where Wisp writes the nginx configurations it owns.
pub fn conf_dir(prefix: &Path) -> PathBuf {
    prefix.join("conf")
}

/// Generated per-project server blocks, `include`d by the main config.
pub fn vhosts_dir(prefix: &Path) -> PathBuf {
    conf_dir(prefix).join("wisp-sites")
}

/// The main config Wisp runs nginx with, leaving the stock `nginx.conf` alone.
pub fn main_config_path(prefix: &Path) -> PathBuf {
    conf_dir(prefix).join("wisp.conf")
}

/// Per-project generated `php.ini` and logs.
pub fn site_dir(slug: &str) -> PathBuf {
    crate::config::sites().join(slug)
}

pub fn site_logs(slug: &str) -> PathBuf {
    site_dir(slug).join("logs")
}

/// The main nginx configuration.
pub fn main_config() -> String {
    "\
worker_processes  1;
pid        logs/nginx.pid;
error_log  logs/error.log;

events {
    worker_connections  1024;
}

http {
    include       mime.types;
    default_type  application/octet-stream;

    access_log    logs/access.log;

    # Windows has no efficient sendfile; nginx docs recommend disabling it.
    sendfile           off;
    keepalive_timeout  65;
    client_max_body_size 128m;

    include       wisp-sites/*.conf;
}
"
    .to_string()
}

/// The port nginx listens on for HTTP. Port 80 by default, overridable via
/// `WISP_HTTP_PORT` for tests or when something else already holds port 80.
pub fn http_port() -> u16 {
    std::env::var("WISP_HTTP_PORT")
        .ok()
        .and_then(|value| value.parse().ok())
        .unwrap_or(80)
}

/// A generated server block for one project.
pub struct Vhost<'a> {
    pub domain: &'a str,
    pub docroot: &'a Path,
    pub port: u16,
    pub listen_port: u16,
    pub log_dir: &'a Path,
    /// `Some` when the project serves HTTPS; the plain port then redirects.
    pub tls: Option<&'a TlsPaths>,
}

impl Vhost<'_> {
    pub fn render(&self) -> String {
        let root = nginx_path(self.docroot);
        let access = nginx_path(&self.log_dir.join("access.log"));
        let error = nginx_path(&self.log_dir.join("error.log"));

        let locations = format!(
            "\
    root  \"{root}\";
    index index.php index.html index.htm;

    location / {{
        try_files $uri $uri/ /index.php?$query_string;
    }}

    location ~ \\.php$ {{
        fastcgi_pass   127.0.0.1:{port};
        fastcgi_index  index.php;
        include        fastcgi_params;
        fastcgi_param  SCRIPT_FILENAME  $document_root$fastcgi_script_name;
    }}

    # Never serve dotfiles, except the ACME challenge path.
    location ~ /\\.(?!well-known).* {{
        deny all;
    }}
",
            root = root,
            port = self.port,
        );

        let header = "# Generated by Wisp. Do not edit; change the project in the app instead.";

        match self.tls {
            Some(tls) => format!(
                "{header}\n\
server {{
    listen       {listen_port};
    server_name  {domain};
    return 301 https://$host$request_uri;
}}

server {{
    listen       443 ssl;
    server_name  {domain};

    ssl_certificate      \"{cert}\";
    ssl_certificate_key  \"{key}\";
    ssl_protocols        TLSv1.2 TLSv1.3;

    access_log  \"{access}\";
    error_log   \"{error}\";

{locations}}}
",
                listen_port = self.listen_port,
                domain = self.domain,
                cert = nginx_path(&tls.cert),
                key = nginx_path(&tls.key),
                access = access,
                error = error,
            ),
            None => format!(
                "{header}\n\
server {{
    listen       {listen_port};
    server_name  {domain};

    access_log  \"{access}\";
    error_log   \"{error}\";

{locations}}}
",
                listen_port = self.listen_port,
                domain = self.domain,
                access = access,
                error = error,
            ),
        }
    }
}

/// Build a per-project `php.ini` from the runtime's `php.ini-development`
/// template: enable every extension the build offers, and append the
/// development overrides Wisp wants.
///
/// `extension_dir` must be set before any `extension=` line, or PHP cannot find
/// the DLLs, so it goes at the very top, ahead of the template.
pub fn php_ini(template: &str, extension_dir: &Path, error_log: &Path) -> String {
    let extension_dir = nginx_path(extension_dir);
    let error_log = nginx_path(error_log);

    let mut out = format!(
        "; ---- Wisp -------------------------------------------------------------\n\
         extension_dir=\"{extension_dir}\"\n"
    );
    out.push_str(&enable_extensions(template));
    out.push_str(&format!(
        "\n\
; ---- Wisp overrides -------------------------------------------------------\n\
cgi.fix_pathinfo=0\n\
extension_dir=\"{extension_dir}\"\n\
log_errors=On\n\
display_errors=On\n\
display_startup_errors=On\n\
error_reporting=E_ALL\n\
error_log=\"{error_log}\"\n\
date.timezone=UTC\n\
memory_limit=512M\n\
upload_max_filesize=64M\n\
post_max_size=64M\n\
max_execution_time=120\n\
",
    ));
    out
}

/// Uncomment the template's `;extension=` lines, so a project behaves like a
/// full development build (intl, mbstring, curl, gd, pdo_mysql, …).
fn enable_extensions(template: &str) -> String {
    let mut out = String::with_capacity(template.len());
    for line in template.lines() {
        match line.strip_prefix(";extension=") {
            Some(rest) => {
                out.push_str("extension=");
                out.push_str(rest.trim_start());
            }
            None => out.push_str(line),
        }
        out.push('\n');
    }
    out
}

/// The document root for a project: `public/` when that is how the app is laid
/// out (Laravel, Symfony), otherwise the root itself.
pub fn resolve_docroot(root: &Path) -> PathBuf {
    if root.join("index.php").is_file() {
        return root.to_path_buf();
    }
    let public = root.join("public");
    if public.join("index.php").is_file() {
        return public;
    }
    root.to_path_buf()
}

/// nginx wants forward slashes, even on Windows.
fn nginx_path(path: &Path) -> String {
    path.to_string_lossy().replace('\\', "/")
}

#[cfg(test)]
mod tests {
    use super::{php_ini, resolve_docroot, Vhost};
    use std::path::{Path, PathBuf};

    #[test]
    fn a_vhost_points_at_the_docroot_and_fastcgi_port() {
        let vhost = Vhost {
            domain: "myapp.test",
            docroot: Path::new(r"C:\Sites\myapp\public"),
            port: 9071,
            listen_port: 80,
            log_dir: Path::new(r"C:\Users\me\.config\wisp\sites\myapp\logs"),
            tls: None,
        }
        .render();

        assert!(vhost.contains("listen       80;"));
        assert!(vhost.contains("server_name  myapp.test;"));
        assert!(vhost.contains("root  \"C:/Sites/myapp/public\";"));
        assert!(vhost.contains("fastcgi_pass   127.0.0.1:9071;"));
        assert!(vhost.contains("try_files $uri $uri/ /index.php?$query_string;"));
        assert!(vhost.contains(r#"error_log   "C:/Users/me/.config/wisp/sites/myapp/logs/error.log";"#));
    }

    #[test]
    fn a_tls_vhost_redirects_and_serves_443() {
        let tls = crate::tls::TlsPaths {
            cert: PathBuf::from(r"C:\certs\myapp.test\cert.pem"),
            key: PathBuf::from(r"C:\certs\myapp.test\key.pem"),
        };
        let vhost = Vhost {
            domain: "myapp.test",
            docroot: Path::new(r"C:\Sites\myapp\public"),
            port: 9071,
            listen_port: 80,
            log_dir: Path::new(r"C:\logs"),
            tls: Some(&tls),
        }
        .render();

        assert!(vhost.contains("listen       443 ssl;"));
        assert!(vhost.contains(r#"ssl_certificate      "C:/certs/myapp.test/cert.pem";"#));
        assert!(vhost.contains(r#"ssl_certificate_key  "C:/certs/myapp.test/key.pem";"#));
        assert!(vhost.contains("return 301 https://$host$request_uri;"));
    }

    #[test]
    fn extensions_are_enabled_after_the_extension_dir() {        let ini = php_ini(
            ";extension=intl\n;extension=curl\nmemory_limit=128M\n",
            Path::new(r"C:\php\ext"),
            Path::new(r"C:\logs\php-error.log"),
        );
        assert!(ini.contains("extension=intl"));
        assert!(ini.contains("extension=curl"));
        assert!(!ini.contains(";extension=intl"));
        let dir_at = ini.find("extension_dir=").expect("extension_dir is set");
        let intl_at = ini.find("extension=intl").expect("intl is enabled");
        assert!(
            dir_at < intl_at,
            "extension_dir must come before any extension"
        );
    }

    #[test]
    fn php_overrides_are_appended_after_the_template() {
        let ini = php_ini(
            "memory_limit=128M\n",
            Path::new(r"C:\php\ext"),
            Path::new(r"C:\logs\php-error.log"),
        );
        // The override must win, which means appearing later in the file.
        let template_at = ini.find("memory_limit=128M").unwrap();
        let override_at = ini.find("memory_limit=512M").unwrap();
        assert!(override_at > template_at);
        assert!(ini.contains(r#"extension_dir="C:/php/ext""#));
        assert!(ini.contains("cgi.fix_pathinfo=0"));
        assert!(ini.contains(r#"error_log="C:/logs/php-error.log""#));
    }

    #[test]
    fn a_public_folder_is_used_when_present() {        let root = std::env::temp_dir().join("wisp-docroot-test");
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(root.join("public")).unwrap();
        std::fs::write(root.join("public").join("index.php"), "<?php").unwrap();

        assert_eq!(resolve_docroot(&root), root.join("public"));

        // Once the app evolves to put index.php at the root, that wins.
        std::fs::write(root.join("index.php"), "<?php").unwrap();
        assert_eq!(resolve_docroot(&root), root);

        let _ = std::fs::remove_dir_all(&root);
        let _ = root;
        let _: PathBuf = PathBuf::new();
    }

    /// Writes a generated ini for the newest installed PHP and asks that PHP to
    /// list its modules, proving `intl` (and friends) actually load.
    /// Ignored by default; run with `cargo test -- --ignored`.
    #[test]
    #[ignore = "needs an installed PHP runtime"]
    fn generated_ini_loads_extensions() {
        let php_root = crate::config::runtimes().join("php");
        let Some(dir) = std::fs::read_dir(&php_root).ok().and_then(|entries| {
            entries
                .flatten()
                .map(|entry| entry.path())
                .find(|path| path.join("php.exe").is_file())
        }) else {
            eprintln!("no installed PHP runtime; skipping");
            return;
        };

        let template = std::fs::read_to_string(dir.join("php.ini-development")).unwrap_or_default();
        let ini = php_ini(
            &template,
            &dir.join("ext"),
            &std::env::temp_dir().join("wisp-error.log"),
        );
        let ini_path = std::env::temp_dir().join("wisp-generated-php.ini");
        std::fs::write(&ini_path, ini).unwrap();

        let output = std::process::Command::new(dir.join("php.exe"))
            .arg("-c")
            .arg(&ini_path)
            .arg("-m")
            .output()
            .expect("php.exe should run");
        let modules = String::from_utf8_lossy(&output.stdout).to_lowercase();
        assert!(modules.contains("intl"), "intl should be loaded:\n{modules}");
        assert!(modules.contains("curl"), "curl should be loaded");

        let _ = std::fs::remove_file(&ini_path);
    }
}
